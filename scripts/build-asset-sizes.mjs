// Writes src/sprites/assetSizes.ts: the pixel size of every original object PNG, so each one is drawn 1:1.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../public/assets/pixel/objects/', import.meta.url);
const sizes = {};
for (const file of readdirSync(dir).filter(name => name.endsWith('.png')).sort()) {
  const bytes = readFileSync(new URL(file, dir));
  sizes[file] = [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
}
writeFileSync(new URL('../src/sprites/assetSizes.ts', import.meta.url), `// Generated by scripts/build-asset-sizes.mjs. Do not edit by hand.\nexport const ASSET_SIZES: Record<string, [number, number]> = ${JSON.stringify(sizes)};\n`);
console.log(Object.keys(sizes).length, 'assets');
