// Generates shared/maps/vivo.js from the measured reference specification.
// Run: node scripts/build-map-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'docs/references/vivo/vivo-map-spec.json'), 'utf8'));
// The reference collision map is authoritative: furniture snapped onto wall bands does not block walking.
const collisions = new Set(JSON.parse(readFileSync(join(root, 'docs/references/vivo/gather-collisions.json'), 'utf8')).collisionsMap.map(([tile]) => tile));
const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const areaIndex = new Map(spec.areas.map((area, index) => [area.id, index]));

const areas = spec.areas.map((area) => ({
  id: area.id.slice(0, 8),
  name: area.displayName.replace(/^👥/, ''),
  type: area.mapAreaType,
  parent: area.parentAreaId ? spec.areas[areaIndex.get(area.parentAreaId)].id.slice(0, 8) : null,
  x: area.absolutePosition.x, y: area.absolutePosition.y,
  w: area.dimensionsInTiles.width, h: area.dimensionsInTiles.height,
  depth: area.depth,
  capacity: area.capacity ?? null,
  floor: area.floorTexture, floorColor: area.floorColor,
  walls: area.isWalled ? area.wallsTexture : null,
  doorways: Object.values(area.doorways?.[0] ?? {}).map((door) => ({ x: door.origin.x, y: door.origin.y, orientation: door.orientation })),
}));

const objects = spec.objects.map((object) => ({
  id: object.id.slice(0, 8),
  parent: object.parent ? object.parent.slice(0, 8) : null,
  kind: slug(object.type),
  family: object.family,
  color: object.color,
  facing: object.orientation,
  // Pixel position of the sprite's origin; the sprite image is placed at (x - originX, y - originY).
  x: Math.round(object.abs.x * 32 * 1000) / 1000, y: Math.round(object.abs.y * 32 * 1000) / 1000,
  w: object.dims.width, h: object.dims.height,
  originX: object.originX, originY: object.originY,
  desk: object.isDesk || undefined,
  seat: object.isSeat ? object.sitTiles.map((tile) => [tile.x, tile.y]) : undefined,
  blocks: object.collisionTiles.some((hash) => collisions.has(hash)) ? object.collisionTiles.filter((hash) => collisions.has(hash)).map((hash) => hash.split('/').map(Number)) : undefined,
  wall: object.collisionTiles.length && !object.collisionTiles.some((hash) => collisions.has(hash)) ? true : undefined,
  // Intrinsic footprint of the catalog item, before the reference's wall-snapping removed it.
  footprint: object.collisionTiles.length ? object.collisionTiles.map((hash) => hash.split('/').map(Number)) : undefined,
}));

const header = `// Generated by scripts/build-map-data.mjs from docs/references/vivo/vivo-map-spec.json.
// Measurements of the reference office "Vivo" (Gather 2.0, floor 1). Do not edit by hand.
`;
// Additions requested by the user on top of the reference: a laptop on every office desk.
const extras = objects.filter((object) => object.kind === 'office-desk').map((desk, index) => ({
  id: `extra-laptop-${index}`, parent: desk.id, kind: 'laptop-computer', family: 'Computer Set', color: 'white', facing: 'Down',
  x: desk.x, y: desk.y - 4, w: 20, h: 28, originX: 10, originY: 26,
}));

const body = `export const TILE = 32;
export const WORLD = Object.freeze({ cols: ${spec.world.tilesX}, rows: ${spec.world.tilesY}, width: ${spec.world.pixelsX}, height: ${spec.world.pixelsY} });
export const AREAS = ${JSON.stringify(areas)};
export const OBJECTS = ${JSON.stringify(objects.map(({ footprint, ...object }) => object))};
/** Objects added for this office on top of the measured reference (see the generator). */
export const EXTRA_OBJECTS = ${JSON.stringify(extras)};
`;
writeFileSync(join(root, 'shared/maps/vivo.js'), header + body);
console.log(`areas ${areas.length}, objects ${objects.length}`);

